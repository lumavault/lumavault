// Regenerates src/db/schemas/auth.ts with the Better Auth CLI, then moves every table into
// the auth Postgres schema. Run after changing plugins in auth.ts, then generate an auth
// migration with DB_SCHEMA=auth pnpm db:generate. With --check, exits 1 instead of writing
// when the committed file is out of date.
import { execFile } from "node:child_process";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";

const API_DIR = fileURLToPath(new URL("../../", import.meta.url));
const CONFIG = "src/tools/auth-schema-config.ts";
const TARGET = join(API_DIR, "src/db/schemas/auth.ts");
const HEADER =
  "// Generated by pnpm auth:generate from src/tools/auth-schema-config.ts. Do not edit by hand.\n" +
  'import { authSchema } from "./namespaces.js";\n';

export function toAuthSchema(generated: string): string {
  if (!generated.includes("pgTable(")) {
    throw new Error("Better Auth CLI output has no pgTable calls; its format may have changed");
  }
  const body = generated
    .replace(/^\s*pgTable,\n/m, "")
    .replace(/\bpgTable\(/g, "authSchema.table(");
  return HEADER + body;
}

async function main(check: boolean): Promise<void> {
  const dir = await mkdtemp(join(tmpdir(), "lv-auth-schema-"));
  try {
    const out = join(dir, "auth.ts");
    await promisify(execFile)("pnpm", ["exec", "auth", "generate", "--config", CONFIG, "--output", out, "--yes"], {
      cwd: API_DIR,
    });
    const next = toAuthSchema(await readFile(out, "utf8"));
    const current = await readFile(TARGET, "utf8").catch(() => "");
    if (check) {
      if (next !== current) {
        console.error("src/db/schemas/auth.ts is out of date; run pnpm auth:generate");
        process.exit(1);
      }
      return;
    }
    await writeFile(TARGET, next);
    if (next !== current) {
      console.info("auth tables changed; now run DB_SCHEMA=auth pnpm db:generate");
    }
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  await main(process.argv.includes("--check"));
}
